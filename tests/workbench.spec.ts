import { test, expect } from '@playwright/test';

test('complete natural-video experiment, evidence and project presentation', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/');
  await expect(page.getByRole('button', { name: /Between the trees/ }).first()).toBeVisible();
  await page.getByRole('button', { name: /Between the trees/ }).first().click();
  await expect(page.getByRole('heading', { name: 'Between the trees' })).toBeVisible();
  await page.waitForFunction(() => Array.from(document.images).every(img => img.complete && img.naturalWidth > 0));
  await page.screenshot({ path: 'docs/design/01-workspace.png', fullPage: true });
  await page.getByRole('button', { name: 'Create damaged clip' }).click();
  await expect(page.getByRole('button', { name: 'Run 3 methods' })).toBeEnabled();
  await expect(page.getByText('RIFE ready · CPU · 2 threads')).toBeVisible();
  await page.getByRole('button', { name: 'Run 3 methods' }).click();
  await expect(page.getByText('RECONSTRUCTION COMPLETE')).toBeVisible({ timeout: 90000 });
  await page.getByLabel('Timeline', { exact: true }).fill('17');
  await expect(page.locator('.frame-id')).toContainText('017');
  await expect(page.getByAltText('Reconstructed frame')).toBeVisible();
  await page.getByRole('button', { name: 'Error map', exact: true }).click();
  await expect(page.getByAltText('error frame 17')).toBeVisible();
  await page.getByRole('button', { name: 'Compare', exact: true }).click();
  await page.getByLabel('Comparison divider').fill('45');
  await page.waitForFunction(() => Array.from(document.images).every(img => img.complete && img.naturalWidth > 0));
  await page.screenshot({ path: 'docs/design/02-reconstruction.png', fullPage: true });
  await page.getByRole('button', { name: 'Inspect results' }).click();
  const reportLink = page.getByRole('link', { name: /Reproducible report/ });
  await expect(reportLink).toBeVisible();
  const response = await page.request.get((await reportLink.getAttribute('href'))!);
  const data = await response.json();
  expect(data.source.synthetic).toBe(false);
  expect(data.source.missing[17]).toBe(true);
  expect(data.methods.rife.model.provider).toBe('CPUExecutionProvider');
  expect(data.methods.rife.frames).toHaveLength(40);
  const media = await page.request.get((await page.getByRole('link', { name: 'Download MP4' }).getAttribute('href'))!);
  expect(media.ok()).toBeTruthy(); expect((await media.body()).length).toBeGreaterThan(1000);
  await page.getByRole('button', { name: 'Long missing interval' }).click();
  await expect(page.getByRole('button', { name: 'Long missing interval' })).toHaveAttribute('aria-pressed', 'true');
  await page.screenshot({ path: 'docs/design/03-evaluation.png', fullPage: true });
  await page.getByRole('button', { name: 'The project', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Every missing frame/ })).toBeVisible();
  await expect(page.locator('video')).toHaveAttribute('src', '/media/bmx-rife.mp4');
  await page.screenshot({ path: 'docs/design/04-project.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'docs/design/05-project-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Workspace', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'docs/design/06-workspace-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});

test('keyboard controls, help dialog, source drawer and configuration invalidation', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Black swan', exact: true })).toBeVisible();
  await page.getByRole('heading', { name: 'Black swan', exact: true }).click();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByLabel('Timeline', { exact: true })).toHaveValue('1');
  await page.keyboard.press('Home');
  await expect(page.getByLabel('Timeline', { exact: true })).toHaveValue('0');
  await page.getByRole('button', { name: 'Keyboard shortcuts' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'Source library', exact: true }).click();
  await page.getByRole('button', { name: /Body in motion/ }).click();
  await expect(page.getByRole('heading', { name: 'Body in motion' })).toBeVisible();
  await expect(page.getByRole('complementary', { name: 'Source library' })).not.toBeVisible();
  await page.getByRole('button', { name: 'Create damaged clip' }).click();
  await expect(page.getByRole('button', { name: 'Run 3 methods' })).toBeEnabled();
  await page.getByRole('button', { name: '01 Damage' }).click();
  await page.getByLabel('Dropped frames').fill('0.3');
  await page.getByRole('button', { name: '02 Restore' }).click();
  await expect(page.getByRole('button', { name: 'Run 3 methods' })).toBeDisabled();
  await expect(page.getByText('Create a damaged clip in step 01 first.')).toBeVisible();
});

test('offline engine is explicit and project remains readable without backend', async ({ page }) => {
  await page.route('**/api/**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Local engine unavailable' }) }));
  await page.goto('/');
  await expect(page.getByRole('alert')).toContainText('Local engine unavailable');
  await expect(page.getByRole('button', { name: 'Create damaged clip' })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Retry connection' })).toBeVisible();
  await page.getByRole('button', { name: 'The project', exact: true }).click();
  await expect(page.getByRole('heading', { name: /Every missing frame/ })).toBeVisible();
  await expect(page.getByRole('alert')).not.toBeVisible();
  await page.getByRole('button', { name: 'Evaluation', exact: true }).click();
  await expect(page.getByRole('table')).toBeVisible();
  await expect(page.getByText('20.79', { exact: false })).toBeVisible();
});
